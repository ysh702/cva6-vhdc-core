#!/usr/bin/env python3
"""Generate the board preload table from the frozen VV35 .mem bundle."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


MASK256 = (1 << 256) - 1
GUARD_PATTERN = int(
    "5a5a5a5a5a5a5a5a5a5a5a5a5a5a5a5a"
    "a5a5a5a5a5a5a5a5a5a5a5a5a5a5a5a5",
    16,
)


def popcount(value: int) -> int:
    """Python 3.8-compatible population count for Vivado 2024.2 hosts."""
    return bin(value).count("1")


def read_words(path: Path) -> list[int]:
    words = []
    for raw in path.read_text(encoding="ascii").splitlines():
        text = raw.split("//", 1)[0].split("#", 1)[0].strip()
        if text:
            words.append(int(text.replace("_", ""), 16))
    return words


def qwords(value: int, width: int) -> list[int]:
    assert width % 64 == 0
    return [(value >> bit) & ((1 << 64) - 1) for bit in range(0, width, 64)]


def add_row(pairs: list[tuple[int, int]], row: int, value: int) -> None:
    for bank, data in enumerate(qwords(value, 256)):
        pairs.append(((bank << 6) | row, data))


def add_hv(pairs: list[tuple[int, int]], slot: int, value: int) -> None:
    words = qwords(value, 1024)
    for row_offset in range(4):
        for bank in range(4):
            pairs.append(((bank << 6) | (slot * 4 + row_offset),
                          words[row_offset * 4 + bank]))


def sha256_tree(paths: list[Path]) -> str:
    digest = hashlib.sha256()
    for path in sorted(paths, key=lambda p: p.name):
        digest.update(path.name.encode("utf-8") + b"\0")
        digest.update(path.read_bytes())
    return digest.hexdigest()


def render(bundle: Path) -> str:
    required = {
        "seed": "master_seed.mem",
        "x": "pmul_point_x.mem",
        "y": "pmul_point_y.mem",
        "k": "pmul_scalars.mem",
        "expected_x": "pmul_expected_x.mem",
        "expected_y": "pmul_expected_y.mem",
        "train": "hdc_train_samples.mem",
        "role": "hdc_role_vectors.mem",
    }
    data = {name: read_words(bundle / leaf) for name, leaf in required.items()}
    for name in ("seed", "x", "y", "k", "expected_x", "expected_y"):
        if len(data[name]) != 1:
            raise ValueError(f"{required[name]} must contain exactly one vector")
    if len(data["train"]) < 1 or len(data["role"]) < 2:
        raise ValueError("HDC bundle does not contain train[0] and role[1]")

    query = data["train"][0] ^ data["role"][1]
    prototypes = [
        query,
        query ^ ((1 << 1024) - 1),
        query ^ int("01" * 512, 2),
        query ^ int("0001" * 256, 2),
    ]
    expected_score = popcount(query)
    if expected_score != 505:
        raise ValueError(f"expected query popcount 505, got {expected_score}")

    seed = data["seed"][0]
    guard3 = ((seed & ((1 << 192) - 1)) << 64) | (0x31C00003 << 32)
    guard6 = guard3 ^ MASK256
    guard7 = guard3 ^ GUARD_PATTERN

    pairs: list[tuple[int, int]] = []
    for row, value in (
        (0, data["x"][0]),
        (1, data["y"][0]),
        (2, data["k"][0]),
        (3, guard3),
        (4, 0),
        (5, 0),
        (6, guard6),
        (7, guard7),
    ):
        add_row(pairs, row, value)
    add_hv(pairs, 3, query)
    for offset, prototype in enumerate(prototypes):
        add_hv(pairs, 4 + offset, prototype)

    files = [bundle / leaf for leaf in required.values()]
    lines = [
        "/* Generated by gen_vv35_board_vectors.py. Do not edit manually. */",
        f"/* vector_bundle_sha256={sha256_tree(files)} */",
        f"/* scalar_k={data['k'][0]:064x}, weight={popcount(data['k'][0])} */",
        ".equ VV35_PRELOAD_PAIR_COUNT, %d" % len(pairs),
        ".equ VV35_EXPECTED_HMATCH, 0x00000000000001f9",
        ".equ VV35_HMATCH_OPERAND, 0x0000000000000443",
        ".equ VV35_PMUL_OPERAND, 0x0000000060004002",
        "",
        ".section .rodata.vv35_vectors, \"a\", @progbits",
        ".balign 16",
        ".global vv35_preload_pairs",
        "vv35_preload_pairs:",
    ]
    for address, value in pairs:
        lines.append(f"    .quad 0x{address:016x}, 0x{value:016x}")

    def emit_row(label: str, value: int) -> None:
        lines.extend(["", ".balign 16", f"{label}:"])
        lines.extend(f"    .quad 0x{word:016x}" for word in qwords(value, 256))

    emit_row("vv35_expected_x", data["expected_x"][0])
    emit_row("vv35_expected_y", data["expected_y"][0])
    emit_row("vv35_expected_guard3", guard3)
    emit_row("vv35_expected_guard6", guard6)
    emit_row("vv35_expected_guard7", guard7)
    lines.extend([
        "",
        ".section .rodata.vv35_metadata, \"a\", @progbits",
        ".balign 4",
        "vv35_vector_metadata:",
        f"    .asciz \"K={data['k'][0]:064x};weight={popcount(data['k'][0])};score={expected_score}\"",
    ])
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("bundle", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    rendered = render(args.bundle)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered, encoding="ascii", newline="\n")
    manifest = {
        "schema": "vv35-board-vector-include-v1",
        "bundle": str(args.bundle),
        "output": str(args.output),
        "output_sha256": hashlib.sha256(rendered.encode("ascii")).hexdigest(),
    }
    print(json.dumps(manifest, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
